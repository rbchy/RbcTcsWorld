/** One line for order pages: "Ada Lovelace, 12 Main St, Apt 4, Pittsburgh, PA 15213". */
export function addressLine(a) {
  if (!a) return '';
  return [a.fullName, a.line1, a.line2, a.city, `${a.state} ${a.zip}`].filter(Boolean).join(', ');
}
